"""Turn the saved runs (reports/runs/*.jsonl) into reports/evaluation.md."""

from __future__ import annotations

import json
import statistics
from collections import defaultdict
from pathlib import Path

from app.config import PROJECT_ROOT

RUNS_DIR = PROJECT_ROOT / "reports" / "runs"
REPORT_PATH = PROJECT_ROOT / "reports" / "evaluation.md"
MAIN_CONFIG = ("openai/gpt-oss-120b", "full")
LANGUAGE_NAMES = {"en": "English", "ar": "Arabic"}


def load_runs(runs_dir: Path = RUNS_DIR) -> dict[tuple[str, str], list[dict]]:
    runs: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for path in sorted(runs_dir.glob("*.jsonl")):
        for line in path.read_text(encoding="utf-8").splitlines():
            record = json.loads(line)
            runs[(record["model"], record["prompt_style"])].append(record)
    return dict(runs)


def _fingerprints(records: list[dict]) -> str:
    pairs = sorted({(r["prompt_style"], r.get("prompt_hash", "none")) for r in records})
    return ", ".join(f"{style} `{fingerprint}`" for style, fingerprint in pairs)


def _pct(part: int, whole: int) -> str:
    return f"{100 * part / whole:.1f}% ({part}/{whole})" if whole else "n/a"


def summarize(records: list[dict]) -> dict[str, str]:
    answerable = [r for r in records if r["answerable"]]
    unanswerable = [r for r in records if not r["answerable"]]
    tokens = [r["prompt_tokens"] + r["completion_tokens"] for r in records]
    return {
        "accuracy": _pct(sum(r["correct"] for r in answerable), len(answerable)),
        "first_try": _pct(sum(r["first_try_correct"] for r in answerable), len(answerable)),
        "refused": f"{sum(r['correct'] for r in unanswerable)}/{len(unanswerable)}",
        "errors": str(sum(r["status"] == "error" for r in records)),
        "latency": f"{statistics.median(r['latency_ms'] for r in records) / 1000:.2f} s",
        "tokens": f"{statistics.mean(tokens):,.0f}" if tokens else "n/a",
    }


def build_report(runs: dict[tuple[str, str], list[dict]]) -> str:
    if not runs:
        return "# Evaluation\n\nNo runs yet. Run `python -m evaluation.run_eval`.\n"

    all_records = [r for records in runs.values() for r in records]
    last_run = max(r["run_at"] for r in all_records)
    question_ids = {r["id"] for r in all_records}
    unanswerable_ids = {r["id"] for r in all_records if not r["answerable"]}
    total, refusals = len(question_ids), len(unanswerable_ids)
    lines = [
        "# Evaluation",
        "",
        f"Generated by `python -m evaluation.run_eval`. Last run: {last_run[:10]}.",
        "",
        "## Method",
        "",
        f"- {total} questions about the `sales` table, each asked in English and in Arabic"
        f" (Modern Standard and Jordanian dialect): {2 * total} runs per configuration.",
        f"- {total - refusals} questions can be answered from the table. {refusals} cannot,"
        " and the right behaviour is to refuse. The prompt lists what the table does not"
        " contain (costs or profit, salespeople, stock): q19 and q20 ask about items on that"
        " list, while q21 and q22 ask about things no note mentions (ratings, shipping time).",
        "- **Execution accuracy**: the model's query returns the same result as a"
        " hand-written gold query. Rows are compared as a set (in order for ranked lists),"
        " numbers are rounded to 2 decimals, and extra columns are allowed.",
        "- **First try**: correct without the self-correction retry.",
        "- Each result stores a fingerprint of the exact prompt; results from an older prompt"
        f" are run again. Fingerprints in this report: {_fingerprints(all_records)}.",
        "- Models run on Groq's free tier with `reasoning_effort=low` and `temperature=0`.",
        "",
        "## Results",
        "",
        "| Model | Prompt | Questions | Execution accuracy | First try | Refused unanswerable"
        " | Errors | Median latency | Tokens per question |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for (model, style), records in runs.items():
        groups = [("All", records)] + [
            (LANGUAGE_NAMES[lang], [r for r in records if r["lang"] == lang])
            for lang in ("en", "ar")
        ]
        for label, group in groups:
            if not group:
                continue
            s = summarize(group)
            lines.append(
                f"| {model.split('/')[-1]} | {style} | {label} | {s['accuracy']} | {s['first_try']}"
                f" | {s['refused']} | {s['errors']} | {s['latency']} | {s['tokens']} |"
            )

    main = runs.get(MAIN_CONFIG)
    if main:
        by_question: dict[str, dict[str, dict]] = defaultdict(dict)
        for record in main:
            by_question[record["id"]][record["lang"]] = record
        lines += [
            "",
            f"## Per question ({MAIN_CONFIG[0].split('/')[-1]}, {MAIN_CONFIG[1]} prompt)",
            "",
            "| # | Category | Question | English | Arabic |",
            "|---|---|---|---|---|",
        ]
        for qid, per_lang in sorted(by_question.items()):
            english = per_lang.get("en", {})
            marks = [
                "✓" if per_lang.get(lang, {}).get("correct") else "✗" if lang in per_lang else ""
                for lang in ("en", "ar")
            ]
            category = next(iter(per_lang.values()))["category"]
            lines.append(
                f"| {qid} | {category} | {english.get('question', '')} | {marks[0]} | {marks[1]} |"
            )

        wrong = [r for r in main if not r["correct"]]
        lines += ["", "## Wrong answers", ""]
        if not wrong:
            lines.append("None.")
        for record in sorted(wrong, key=lambda r: (r["id"], r["lang"])):
            lines.append(
                f"- **{record['id']} ({LANGUAGE_NAMES[record['lang']]})**: {record['question']}"
                f" — status `{record['status']}`"
                + (f", error: {record['error']}" if record["error"] else "")
            )
            if record["sql"]:
                lines += ["", "  ```sql", *[f"  {x}" for x in record["sql"].splitlines()], "  ```"]
    return "\n".join(lines) + "\n"


def write_report(runs_dir: Path = RUNS_DIR, report_path: Path = REPORT_PATH) -> Path:
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(build_report(load_runs(runs_dir)), encoding="utf-8")
    return report_path


if __name__ == "__main__":
    print(f"Report written to {write_report()}")
